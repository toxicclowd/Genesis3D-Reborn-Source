grBoolean D3D12Shaders_Load(ID3D12Device* Device)
{
	D3D12Shaders_Unload();
	if (!Device)
		return GR_FALSE;

	char SourceDir[MAX_PATH] = "";
	const bool bLooseSource = D3D12Config_GetString("Shaders", "SourceDir", SourceDir, sizeof(SourceDir));
	const bool bSM6 = DeviceSupportsSM6(Device);
	const bool bRuntime = bLooseSource || !bSM6 || D3D12Config_GetBool("Shaders", "RuntimeCompile", false);

	if (bLooseSource)
		D3D12Log::GetPtr()->Printf("Shaders: compiling from %s", SourceDir);
	else if (!bSM6)
		D3D12Log::GetPtr()->Printf("Shaders: device has no SM 6.0, compiling embedded source as SM 5.0");
	else if (bRuntime)
		D3D12Log::GetPtr()->Printf("Shaders: RuntimeCompile set, compiling embedded source as SM 5.0");
	else
		D3D12Log::GetPtr()->Printf("Shaders: using precompiled DXIL (SM 6.0)");

	for (int Id = 0; Id < SHADER_COUNT; ++Id)
	{
		const ShaderDesc& Desc = Shaders[Id];

		if (bRuntime)
		{
			std::vector<char> Source;
			char Path[MAX_PATH] = "";
			bool bHaveSource = false;

			if (bLooseSource)
			{
				char Relative[MAX_PATH];
				sprintf_s(Relative, "%s\\%s", SourceDir, Desc.File);
				D3D12Config_ResolvePath(Relative, Path, sizeof(Path));
				bHaveSource = ReadFileText(Path, Source);
				if (!bHaveSource)
					D3D12Log::GetPtr()->Printf("WARNING: Shaders: cannot read %s, using the embedded copy", Path);
			}
			if (!bHaveSource)
			{
				strcpy_s(Path, Desc.File);
				bHaveSource = ReadResourceText(Desc.ResourceId, Source);
			}

			if (bHaveSource)
				Compiled[Id] = CompileSource(Source, Path, Desc);

			if (Compiled[Id])
			{
				Bytecode[Id].pShaderBytecode = Compiled[Id]->GetBufferPointer();
				Bytecode[Id].BytecodeLength = Compiled[Id]->GetBufferSize();
				continue;
			}

			// A pipeline cannot mix DXBC and DXIL, so one failure means none of the
			// run-time shaders can be used. On an SM 6.0 device the shaders the driver
			// was built with still work (for example after a bad edit in SourceDir).
			D3D12Shaders_Unload();
			if (!bSM6)
				return GR_FALSE;
			D3D12Log::GetPtr()->Printf("WARNING: Shaders: run-time compile failed, using the precompiled DXIL for all shaders");
			for (int Each = 0; Each < SHADER_COUNT; ++Each)
			{
				Bytecode[Each].pShaderBytecode = Shaders[Each].Dxil;
				Bytecode[Each].BytecodeLength = Shaders[Each].DxilSize;
			}
			return GR_TRUE;
		}

		Bytecode[Id].pShaderBytecode = Desc.Dxil;
		Bytecode[Id].BytecodeLength = Desc.DxilSize;
	}

	return GR_TRUE;
}

void D3D12Shaders_Unload()
{
	for (int Id = 0; Id < SHADER_COUNT; ++Id)
	{
		Compiled[Id].Reset();
		Bytecode[Id] = D3D12_SHADER_BYTECODE{};
	}
}

D3D12_SHADER_BYTECODE D3D12Shaders_Get(D3D12_SHADER_ID Id)
{
	if (Id < 0 || Id >= SHADER_COUNT)
		return D3D12_SHADER_BYTECODE{};
	return Bytecode[Id];
}

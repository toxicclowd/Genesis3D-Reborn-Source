	bool DeviceSupportsSM6(ID3D12Device* Device)
	{
		D3D12_FEATURE_DATA_SHADER_MODEL Model = { D3D_SHADER_MODEL_6_0 };
		return SUCCEEDED(Device->CheckFeatureSupport(D3D12_FEATURE_SHADER_MODEL, &Model, sizeof(Model))) &&
			Model.HighestShaderModel >= D3D_SHADER_MODEL_6_0;
	}

	bool ReadFileText(const char* Path, std::vector<char>& Out)
	{
		FILE* File = nullptr;
		if (fopen_s(&File, Path, "rb") != 0 || !File)
			return false;
		fseek(File, 0, SEEK_END);
		const long Size = ftell(File);
		fseek(File, 0, SEEK_SET);
		Out.resize(Size > 0 ? static_cast<size_t>(Size) : 0);
		const bool Ok = Size >= 0 && fread(Out.data(), 1, Out.size(), File) == Out.size();
		fclose(File);
		return Ok;
	}

	bool ReadResourceText(int ResourceId, std::vector<char>& Out)
	{
		HMODULE Module = D3D12Config_Module();
		HRSRC Resource = FindResourceA(Module, MAKEINTRESOURCEA(ResourceId), MAKEINTRESOURCEA(10) /* RT_RCDATA */);
		HGLOBAL Handle = Resource ? LoadResource(Module, Resource) : nullptr;
		const void* Data = Handle ? LockResource(Handle) : nullptr;
		if (!Data)
			return false;
		const DWORD Size = SizeofResource(Module, Resource);
		Out.assign(static_cast<const char*>(Data), static_cast<const char*>(Data) + Size);
		return true;
	}

	ComPtr<ID3DBlob> CompileSource(const std::vector<char>& Source, const char* Name, const ShaderDesc& Desc)
	{
		ComPtr<ID3DBlob> Shader;
		ComPtr<ID3DBlob> Errors;
		UINT Flags = D3DCOMPILE_ENABLE_STRICTNESS;
#ifdef _DEBUG
		Flags |= D3DCOMPILE_DEBUG | D3DCOMPILE_SKIP_OPTIMIZATION;
#else
		Flags |= D3DCOMPILE_OPTIMIZATION_LEVEL3;
#endif
		// The bindless shaders index the whole descriptor heap.
		if (Desc.Bindless)
			Flags |= D3DCOMPILE_ENABLE_UNBOUNDED_DESCRIPTOR_TABLES;
		const D3D_SHADER_MACRO Bindless[] = { { "G3D_BINDLESS", "1" }, { nullptr, nullptr } };
		const HRESULT Hr = D3DCompile(
			Source.data(), Source.size(), Name, Desc.Bindless ? Bindless : nullptr, nullptr,
			Desc.Entry, Desc.RuntimeTarget, Flags, 0, &Shader, &Errors);
		if (FAILED(Hr))
		{
			D3D12Log::GetPtr()->Printf(
				"ERROR: %s:%s compilation failed (0x%08X): %s",
				Name, Desc.Entry, Hr,
				Errors ? static_cast<const char*>(Errors->GetBufferPointer()) : "no compiler details");
			return nullptr;
		}
		return Shader;
	}
